"""Generate a logging proxy for a renderer DLL: python gen.py <real.dll> <outdir> <REAL_NAME>
Every export of <real.dll> is logged (name + first 6 stack args) to .\\system\\trace_proxy.log and
forwarded to <REAL_NAME>. Build: i686-w64-mingw32-g++ -shared -O2 -DREAL_DLL=\\"tridx8.orig.dll\\" proxy.cxx thunks.S proxy.def -o tridx8.dll"""
import sys, pefile, os
pe = pefile.PE(sys.argv[1]); out = sys.argv[2]; os.makedirs(out, exist_ok=True)
names = sorted(s.name.decode() for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name)
n = len(names)
open(f"{out}/proxy.cxx", "w").write(f'''// Generated by gen.py: logs every renderer call, forwards to REAL_DLL.
#include <windows.h>
#include <stdio.h>
static const char* N[]={{{",".join('"%s"' % x for x in names)}}};
extern "C" {{ void* R[{n}]; }}
static FILE* F; static unsigned long C; static unsigned long Lim = 400000;
extern "C" void __cdecl LogCall(int i, unsigned* a){{ if(!F){{F=fopen(".\\\\system\\\\trace_proxy.log","w");}} if(F && C++<Lim){{fprintf(F,"%s(%08x,%08x,%08x,%08x,%08x,%08x)\\n",N[i],a[0],a[1],a[2],a[3],a[4],a[5]);}} }}
extern "C" void __cdecl Load(){{ HMODULE h=LoadLibraryA(REAL_DLL); for(int i=0;i<{n};i++) R[i]=(void*)GetProcAddress(h,N[i]); }}
BOOL WINAPI DllMain(HINSTANCE,DWORD r,LPVOID){{ if(r==DLL_PROCESS_ATTACH) Load(); if(r==DLL_PROCESS_DETACH && F) fclose(F); return TRUE; }}
''')
s = [".intel_syntax noprefix", ".text"]
for i, x in enumerate(names):
    s += [f".globl _T_{x}", f"_T_{x}:", "  pushad", "  lea eax,[esp+36]", "  push eax", f"  push {i}",
          "  call _LogCall", "  add esp,8", "  popad", f"  jmp dword ptr [_R+{i*4}]"]
open(f"{out}/thunks.S", "w").write("\n".join(s) + "\n")
open(f"{out}/proxy.def", "w").write('LIBRARY "tridx8.dll"\nEXPORTS\n' + "".join(f"    {x} = T_{x}\n" for x in names))
